def calcPathGeometry(path, target=None, start=None, bond_lo=3.4, d13=4.4, bond_hi=4.2, clash_min=3.0,
                     clash_sep=3, tol=0.05):
    """Return, for every frame of *path*, the RMSD to the target and to the start and the chain geometry, measured
    against the same native-aware limits that :func:`.calcNeoAdaptiveANM` enforces.

    The limits are derived from the start and, if given, the target, so that native geometry is never counted as a
    violation: the floor of each virtual bond is the smaller of *bond_lo* and its native length, the floor of each
    (i, i+2) distance the smaller of *d13* and its native value, the ceiling of each virtual bond the larger of
    *bond_hi* and its native length, and residue pairs already closer than *clash_min* in a native structure are held
    to their native distance instead of *clash_min*. Virtual bonds longer than 4.6 Å in a native structure are chain
    breaks and are excluded from the bond measures.

    The returned :class:`dict` contains one value per frame for:

      * ``'rmsd_target'``, ``'rmsd_start'``: RMSD after optimal superposition (Å)
      * ``'longest_bond'``, ``'shortest_bond'``: virtual bond lengths (Å)
      * ``'bond_excursion'``: largest change of a virtual bond from its length in the start (Å)
      * ``'shortest_i_i2'``: shortest distance between residues two apart (Å)
      * ``'closest_nonbonded'``: closest approach of residues at least *clash_sep* apart (Å)
      * ``'clash_shortfall'``: largest shortfall below *clash_min* among pairs that are not natively close (Å)
      * ``'floor_shortfall'``, ``'ceiling_excess'``, ``'native_pair_shortfall'``: largest violation of the
        native-aware floors, of the bond ceiling, and of the native distance of natively close pairs (Å)
      * ``'admissible'``: whether every limit holds within *tol*
      * ``'midpoint'``: whether the frame is a linear midpoint (see :func:`dropMidpoints`)

    and the limits used (``'limits'``).

    :arg path: the path; its first frame is the start unless *start* is given
    :type path: :class:`.Ensemble`, :class:`.Atomic`, :class:`~numpy.ndarray`

    :arg target: target structure
    :type target: :class:`.Atomic`, :class:`~numpy.ndarray`

    :arg start: start structure, default is the first frame
    :type start: :class:`.Atomic`, :class:`~numpy.ndarray`

    :arg bond_lo: floor of virtual bonds, default is 3.4 Å
    :arg d13: floor of (i, i+2) distances, default is 4.4 Å
    :arg bond_hi: ceiling of virtual bonds, default is 4.2 Å
    :arg clash_min: steric limit for non-bonded pairs, default is 3.0 Å
    :arg clash_sep: minimum sequence separation of non-bonded pairs, default is 3
    :arg tol: tolerance for the admissibility test, default is 0.05 Å (as in NeoAdaptiveANM)
    """
    from .neo_adaptive import build_chain_floors, build_bond_ceiling, build_clash_exempt, build_exempt_floors

    X = _frames(path)
    n = X.shape[1]
    S = _coords(start, n, 'start') if start is not None else X[0].copy()
    T = _coords(target, n, 'target')
    natives = [S] if T is None else [S, T]

    bonded = np.all([_bond_lengths(Z) <= BREAK_DIST for Z in natives], axis=0)
    bond_floor, d13_floor = build_chain_floors(natives, bond_lo, d13)
    ceiling = build_bond_ceiling(natives, bond_hi)
    exempt = build_clash_exempt(natives, clash_min, clash_sep) if clash_min else set()
    ex_floor = build_exempt_floors(natives, exempt) if exempt else None

    ii, jj = np.triu_indices(n, k=clash_sep)
    not_exempt = np.ones(len(ii), dtype=bool)
    if exempt:
        keys = np.array([min(a, b) * n + max(a, b) for a, b in exempt], dtype=np.int64)
        not_exempt = ~np.isin(ii.astype(np.int64) * n + jj, keys)

    bl0 = _bond_lengths(S)
    zero = np.zeros(len(X))
    out = dict(frame=np.arange(len(X)), rmsd_target=zero.copy(), rmsd_start=_rmsd_fit_many(S, X),
               longest_bond=zero.copy(), shortest_bond=zero.copy(), bond_excursion=zero.copy(),
               shortest_i_i2=zero.copy(), closest_nonbonded=zero.copy(), clash_shortfall=zero.copy(),
               floor_shortfall=zero.copy(), ceiling_excess=zero.copy(), native_pair_shortfall=zero.copy())
    out['rmsd_target'] = _rmsd_fit_many(T, X) if T is not None else np.full(len(X), np.nan)
    for k, Z in enumerate(X):
        bl = _bond_lengths(Z)
        d2 = np.linalg.norm(Z[2:] - Z[:-2], axis=1) if n > 2 else np.array([np.inf])
        dnb = np.linalg.norm(Z[ii] - Z[jj], axis=1) if len(ii) else np.array([np.inf])
        out['longest_bond'][k] = bl[bonded].max() if bonded.any() else np.nan
        out['shortest_bond'][k] = bl.min()
        out['bond_excursion'][k] = np.abs(bl - bl0)[bonded].max() if bonded.any() else np.nan
        out['shortest_i_i2'][k] = d2.min()
        out['closest_nonbonded'][k] = dnb.min()
        if clash_min and not_exempt.any():
            out['clash_shortfall'][k] = max(0.0, clash_min - dnb[not_exempt].min())
        short = 0.0
        if bond_floor is not None:
            short = max(short, (bond_floor - bl).max())
        if d13_floor is not None and n > 2:
            short = max(short, (d13_floor - d2).max())
        out['floor_shortfall'][k] = max(short, 0.0)
        if ceiling is not None:
            out['ceiling_excess'][k] = max(0.0, (bl - ceiling).max())
        if ex_floor is not None:
            pairs, floors = ex_floor
            dex = np.linalg.norm(Z[pairs[:, 0]] - Z[pairs[:, 1]], axis=1)
            out['native_pair_shortfall'][k] = max(0.0, (floors - dex).max())
    viol = np.max([out['clash_shortfall'], out['floor_shortfall'], out['ceiling_excess'],
                   out['native_pair_shortfall']], axis=0)
    out['admissible'] = viol <= tol
    out['midpoint'] = np.ones(len(X), dtype=bool)
    out['midpoint'][dropMidpoints(X, return_indices=True)[1]] = False
    out['limits'] = dict(bond_lo=bond_lo, d13=d13, bond_hi=bond_hi, clash_min=clash_min, clash_sep=clash_sep, tol=tol)
    return out


def showPathGeometry(geometry, label=None, color=None, axes=None, **kwargs):
    """Plot the result of :func:`calcPathGeometry` in four panels: RMSD to the target and to the start, virtual bond
    lengths against their limits, closest non-bonded approach against the steric limit, and the largest violation
    of any limit. Several results can be compared by calling this function again with the returned *axes*.

    :arg geometry: output of :func:`calcPathGeometry`
    :arg label: legend label for this path
    :arg color: line colour
    :arg axes: four Matplotlib axes to draw on, default is a new figure

    Returns the list of axes."""
    g = geometry
    axs = _axes(4, axes)
    c = color or COLORS[0]
    x = g['frame']
    lim = g['limits']
    kw = dict(color=c, lw=1.8)
    kw.update(kwargs)
    if not np.all(np.isnan(g['rmsd_target'])):
        axs[0].plot(x, g['rmsd_target'], label=(label + ', to target') if label else 'to target', **kw)
    axs[0].plot(x, g['rmsd_start'], ls='--', label=(label + ', to start') if label else 'to start', **kw)
    axs[1].plot(x, g['longest_bond'], label=(label + ', longest') if label else 'longest bond', **kw)
    axs[1].plot(x, g['shortest_bond'], ls='--', label=(label + ', shortest') if label else 'shortest bond', **kw)
    axs[2].plot(x, g['closest_nonbonded'], label=label, **kw)
    viol = np.max([g['clash_shortfall'], g['floor_shortfall'], g['ceiling_excess'], g['native_pair_shortfall']], axis=0)
    axs[3].plot(x, viol, label=label, **kw)
    if not getattr(axs[1], '_pt_limits', False):
        axs[1].axhline(lim['bond_hi'], color='0.45', ls=':', lw=1.2)
        axs[1].axhline(lim['bond_lo'], color='0.45', ls=':', lw=1.2)
        axs[1].text(x[-1], lim['bond_hi'], ' ceiling', va='bottom', ha='right', fontsize=FONTSIZE - 2, color='0.35')
        axs[1].text(x[-1], lim['bond_lo'], ' floor', va='top', ha='right', fontsize=FONTSIZE - 2, color='0.35')
        axs[2].axhline(lim['clash_min'], color='0.45', ls=':', lw=1.2)
        axs[2].text(x[-1], lim['clash_min'], 'steric limit', va='bottom', ha='right', fontsize=FONTSIZE - 2, color='0.35')
        axs[3].axhline(lim['tol'], color='0.45', ls=':', lw=1.2)
        axs[3].text(x[-1], lim['tol'], 'tolerance', va='bottom', ha='right', fontsize=FONTSIZE - 2, color='0.35')
        axs[1]._pt_limits = True
    _style_axes(axs[0], 'Frame', 'RMSD (Å)', 'a  RMSD along the path')
    _style_axes(axs[1], 'Frame', 'Virtual bond (Å)', 'b  Virtual bonds')
    _style_axes(axs[2], 'Frame', 'Distance (Å)', 'c  Closest non-bonded approach')
    _style_axes(axs[3], 'Frame', 'Violation (Å)', 'd  Largest violation of any limit')
    axs[0].legend(fontsize=FONTSIZE - 2, frameon=False)
    if label:
        axs[2].legend(fontsize=FONTSIZE - 2, frameon=False)
    return axs


