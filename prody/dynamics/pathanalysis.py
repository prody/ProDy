def dropMidpoints(path, tol=1e-3, return_indices=False):
    """Return the frames of *path* without the linear midpoints that NeoAdaptiveANM stores between accepted
    conformations, so that consecutive frames are consecutive accepted steps.

    A frame is a midpoint when its RMS distance from the average of its two neighbours is below *tol* (Å).
    Frames are examined in order and two consecutive frames are never both dropped, so the alternating pattern of
    NeoAdaptiveANM (conformation, midpoint, conformation, ...) is recovered in every traversal mode, including the
    junction of alternating runs. Paths without midpoints, such as those of :func:`.calcAdaptiveANM`, are returned
    unchanged. A path made of equally spaced points on a straight line cannot be told apart from one with midpoints;
    analyze such paths with ``midpoints=True`` in the functions that offer it.

    :arg path: the path
    :type path: :class:`.Ensemble`, :class:`.Atomic`, :class:`~numpy.ndarray`

    :arg tol: tolerance in Å, default is 0.001
    :type tol: float

    :arg return_indices: also return the indices of the kept frames, default is **False**
    :type return_indices: bool
    """
    X = _frames(path)
    keep = list(range(len(X)))
    if len(X) >= 3:
        mid = np.sqrt(((X[1:-1] - 0.5 * (X[:-2] + X[2:])) ** 2).sum(-1).mean(-1))
        keep, dropped_last = [0], False
        for i in range(1, len(X) - 1):
            if mid[i - 1] <= tol and not dropped_last:
                dropped_last = True
                continue
            keep.append(i)
            dropped_last = False
        keep.append(len(X) - 1)
    keep = np.array(keep, dtype=int)
    return (X[keep], keep) if return_indices else X[keep]


