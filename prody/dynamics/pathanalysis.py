def _densify(frames, spacing):
    out = [frames[0]]
    for X, Y in zip(frames[:-1], frames[1:]):
        k = max(1, int(np.ceil(np.sqrt(((Y - X) ** 2).sum(1).mean()) / spacing)))
        out.extend(X + (Y - X) * t for t in np.linspace(0, 1, k + 1)[1:])
    return np.array(out)


def calcClosestApproach(path, structure, target=None, start=None, indices=None, spacing=None, n_line=101):
    """Return how closely *path* approaches *structure*, for example an experimentally resolved intermediate, and
    compare it with the straight line between the endpoints.

    The path is densified by linear interpolation to the resolution of the straight line, so that both routes are
    compared at the same spacing. Distances are RMSDs after optimal superposition, on the atoms given by *indices*.

    The returned :class:`dict` contains ``'d_path'`` and ``'d_line'``, the closest approach of the path and of the
    straight line, ``'d_end'``, the distance from the nearer endpoint, ``'position_path'`` and ``'position_line'``,
    where along each route (arc-length fraction) the closest approach occurs, ``'outcome'`` (``'path closer'``,
    ``'tie'`` or ``'line closer'``, ties being differences below 0.3 Å), and the profiles ``'profile_path'``,
    ``'profile_line'``, ``'arc_path'`` and ``'arc_line'``.

    :arg path: the path
    :type path: :class:`.Ensemble`, :class:`.Atomic`, :class:`~numpy.ndarray`

    :arg structure: the structure to approach; its atoms correspond to *indices* of the path
    :type structure: :class:`.Atomic`, :class:`~numpy.ndarray`

    :arg target: target of the path, default is its last frame
    :arg start: start of the path, default is its first frame
    :arg indices: atoms of the path that correspond to the atoms of *structure*, default is all atoms (for example
        the indices returned by :func:`.matchChains` when *structure* has missing residues)
    :arg spacing: densification spacing in Å, default is the RMS spacing of the straight line
    :arg n_line: number of frames of the straight line, default is 101"""
    X = _frames(path)
    n = X.shape[1]
    S = _coords(start, n, 'start') if start is not None else X[0]
    T = _coords(target, n, 'target') if target is not None else X[-1]
    idx = np.arange(n) if indices is None else np.asarray(indices, dtype=int)
    C = _coords(structure, len(idx), 'structure')
    T2 = _fit(T, S)
    L = np.array([(1 - t) * S + t * T2 for t in np.linspace(0, 1, n_line)])
    if spacing is None:
        spacing = float(np.sqrt(((T2 - S) ** 2).sum(1).mean())) / (n_line - 1)
    Pd = _densify(X, spacing)
    prof_p = _rmsd_fit_many(C, Pd[:, idx])
    prof_l = _rmsd_fit_many(C, L[:, idx])
    arc_p, arc_l = _arc_fraction(Pd), _arc_fraction(L)
    ip, il = int(prof_p.argmin()), int(prof_l.argmin())
    out = dict(d_path=float(prof_p[ip]), d_line=float(prof_l[il]),
               d_end=float(min(_rmsd_fit(S[idx], C), _rmsd_fit(T[idx], C))),
               position_path=float(arc_p[ip]), position_line=float(arc_l[il]),
               profile_path=prof_p, profile_line=prof_l, arc_path=arc_p, arc_line=arc_l, spacing=spacing)
    diff = out['d_path'] - out['d_line']
    out['outcome'] = 'tie' if abs(diff) < 0.3 else ('path closer' if diff < 0 else 'line closer')
    return out


