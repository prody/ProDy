"""Analysis of conformational transition pathways.

This module analyzes pathways such as those generated by :func:`.calcNeoAdaptiveANM`
and :func:`.calcAdaptiveANM`: whether every frame of a path is physically admissible,
how much elastic work each step costs and which normal modes carry it, how an observed
conformational change decomposes over the normal modes of its starting structure, how
two routes differ, how closely a path approaches a given structure (for example an
experimentally resolved intermediate), and how a Cα path can be turned into an all-atom
trajectory.

Every ``calc...`` function returns a :class:`dict` of NumPy arrays and numbers, and has a
``show...`` companion that plots the result with Matplotlib.

A path can be given as an :class:`.Ensemble` (the output of :func:`.calcNeoAdaptiveANM`),
an :class:`.Atomic` instance with one coordinate set per frame, or an array of shape
``(n_frames, n_atoms, 3)``. Start, target and other single structures can be
:class:`.Atomic` instances or ``(n_atoms, 3)`` arrays whose atoms correspond one to one
to those of the path.

NeoAdaptiveANM stores the linear midpoint between consecutive accepted conformations,
because both are tested; :func:`dropMidpoints` removes these frames, so that functions
working on steps (:func:`calcStepWork`) count accepted steps."""

