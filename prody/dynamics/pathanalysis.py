def calcRouteDistance(path1, path2, indices=None):
    """Return the distance between two routes: for every frame of one path, the RMSD (after optimal superposition)
    to the closest frame of the other, averaged over the frames and over both directions,

    .. math:: \\mathcal{D}(P, P') = \\frac{1}{2} \\left[ \\langle \\min_{Y \\in P'} \\mathrm{RMSD}(X, Y)
              \\rangle_{X \\in P} + \\langle \\min_{X \\in P} \\mathrm{RMSD}(Y, X) \\rangle_{Y \\in P'} \\right]

    The returned :class:`dict` contains ``'distance'``, the two one-way averages ``'d12'`` and ``'d21'``, the
    closest-frame RMSD of every frame (``'profile1'``, ``'profile2'``), the index of that closest frame
    (``'nearest1'``, ``'nearest2'``), and the arc-length fraction of every frame (``'position1'``,
    ``'position2'``). Reverse a path (``path[::-1]``) to compare paths run in opposite directions; the distance
    itself does not depend on the direction.

    :arg path1: first path
    :arg path2: second path, with the same atoms
    :arg indices: atom indices to compare, default is all atoms"""
    P = _frames(path1)
    Q = _frames(path2)
    if P.shape[1] != Q.shape[1]:
        raise ValueError('the two paths have different numbers of atoms')
    if indices is not None:
        P, Q = P[:, indices], Q[:, indices]
    M = np.array([_rmsd_fit_many(x, Q) for x in P])
    out = dict(profile1=M.min(1), nearest1=M.argmin(1), profile2=M.min(0), nearest2=M.argmin(0),
               position1=_arc_fraction(P), position2=_arc_fraction(Q), matrix=M)
    out['d12'] = float(out['profile1'].mean())
    out['d21'] = float(out['profile2'].mean())
    out['distance'] = 0.5 * (out['d12'] + out['d21'])
    return out


