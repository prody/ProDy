def _residue_frames(CA, a, b, c):
    """Orthonormal frame (3 x 3, axes as columns) for every residue from three consecutive Calpha atoms a, b, c of
    its chain segment: the first axis runs from a to c, the second points from their midpoint toward b."""
    e1 = CA[c] - CA[a]
    e1 /= np.linalg.norm(e1, axis=1)[:, None]
    mid = 0.5 * (CA[c] + CA[a])
    v = CA[b] - mid
    v = v - (v * e1).sum(1)[:, None] * e1
    norm = np.linalg.norm(v, axis=1)
    bad = norm < 1e-6
    if bad.any():                     # collinear neighbours: any vector perpendicular to e1
        a = np.where(np.abs(e1[:, :1]) < 0.9, [[1.0, 0, 0]], [[0, 1.0, 0]])
        alt = np.cross(e1, a)
        v[bad] = alt[bad]
        norm = np.linalg.norm(v, axis=1)
    e2 = v / norm[:, None]
    e3 = np.cross(e1, e2)
    return np.stack([e1, e2, e3], axis=2)


def _frame_triples(CA0, keys):
    """For every residue, three consecutive Calpha atoms (a, b, c) of its chain segment that define its local frame:
    the residue and its two neighbours, or, at the end of a segment, the residue and the next two (or previous two).
    Residues in segments shorter than three residues get no frame (usable is False) and are only translated."""
    n = len(CA0)
    bonded = np.zeros(max(n - 1, 0), dtype=bool)
    if n > 1:
        bonded = np.linalg.norm(CA0[1:] - CA0[:-1], axis=1) <= BREAK_DIST
        bonded &= np.array([keys[i][:2] == keys[i + 1][:2] for i in range(n - 1)])
    a, b, c = np.arange(n), np.arange(n), np.arange(n)
    usable = np.zeros(n, dtype=bool)
    for i in range(n):
        left = i > 0 and bonded[i - 1]
        right = i < n - 1 and bonded[i]
        if left and right:
            a[i], b[i], c[i], usable[i] = i - 1, i, i + 1, True
        elif right and i + 2 < n and bonded[i + 1]:           # first residue of a segment
            a[i], b[i], c[i], usable[i] = i, i + 1, i + 2, True
        elif left and i >= 2 and bonded[i - 2]:                # last residue of a segment
            a[i], b[i], c[i], usable[i] = i - 2, i - 1, i, True
    return a, b, c, usable


def buildAllAtomPath(path, reference, method='frame', ref_frame=0, pulchra='pulchra', scwrl=None,
                     pulchra_args=(), keep_files=False):
    """Return an all-atom version of a Cα *path* as an :class:`.AtomGroup` with one coordinate set per frame,
    which can be written with :func:`.writePDB` or :func:`.writeDCD`.

    *reference* is an all-atom structure of the same protein whose Cα atoms correspond, in order, to the atoms of
    the path; normally the all-atom file of the start. Atoms of residues without a Cα (ligands, water) are left
    out. Three methods are available:

      * ``'frame'`` (default, no external programs): every residue is moved as a rigid body by the rotation of a
        local frame built from its own Cα and its two neighbours, and translated with its Cα, so that side
        chains and backbone atoms turn with the chain instead of only sliding.
      * ``'translate'``: every atom is moved by the displacement of its residue's Cα, as in :func:`.extendModel`.
        Residues do not rotate, so backbone and side-chain geometry degrade where the chain bends.
      * ``'pulchra'``: every frame is rebuilt from its Cα trace by PULCHRA (Rotkiewicz and Skolnick 2008),
        and, if *scwrl* is given, its side chains are repacked by SCWRL4 (Krivov et al. 2009). Both programs must be
        installed; give their paths if they are not on the system path. The reference supplies the residue names.

    The ``'frame'`` and ``'translate'`` methods keep the reference's atoms, names and order, so every frame has the
    same topology; neither removes steric clashes between side chains, so the result is a starting point for
    energy minimization rather than a refined model.

    :arg path: Cα path
    :type path: :class:`.Ensemble`, :class:`.Atomic`, :class:`~numpy.ndarray`

    :arg reference: all-atom structure matching the path's Cα atoms
    :type reference: :class:`.Atomic`

    :arg method: ``'frame'``, ``'translate'`` or ``'pulchra'``
    :arg ref_frame: frame of the path that the reference corresponds to, default is 0 (the start); the reference
        is superposed onto this frame first
    :arg pulchra: PULCHRA executable, default is ``'pulchra'``
    :arg scwrl: SCWRL4 executable, default is **None** (no repacking)
    :arg pulchra_args: extra command-line options for PULCHRA
    :arg keep_files: keep the temporary per-frame files of the ``'pulchra'`` method, default is **False**"""
    X = _frames(path)
    if not isinstance(reference, Atomic):
        raise TypeError('reference must be an Atomic instance with all atoms')
    ref = reference.select('protein') or reference
    ca = ref.select('name CA')
    if ca is None or ca.numAtoms() != X.shape[1]:
        raise ValueError('the reference has {0} CA atoms; the path has {1}'.format(
            0 if ca is None else ca.numAtoms(), X.shape[1]))
    ca_keys = list(zip(ca.getSegnames(), ca.getChids(), ca.getResnums(), ca.getIcodes()))
    key_index = {k: i for i, k in enumerate(ca_keys)}
    atom_keys = list(zip(ref.getSegnames(), ref.getChids(), ref.getResnums(), ref.getIcodes()))
    owner = np.array([key_index.get(k, -1) for k in atom_keys])
    keep = owner >= 0
    if not keep.all():
        LOGGER.info('buildAllAtomPath: {0} atoms without a matching CA residue are left out'.format(int((~keep).sum())))
    atoms = ref.copy() if keep.all() else ref.select('index ' + ' '.join(map(str, ref.getIndices()[keep]))).copy()
    owner = owner[keep]
    R0 = atoms.getCoords()
    CA_ref = ca.getCoords()
    rot, tr = _kabsch(CA_ref, X[ref_frame])
    R0 = R0 @ rot + tr
    CA0 = CA_ref @ rot + tr
    resid = float(np.sqrt(((CA0 - X[ref_frame]) ** 2).sum(1).mean()))
    if resid > 0.5:
        LOGGER.warn('buildAllAtomPath: the reference CA atoms differ from frame {0} of the path by {1:.2f} A RMSD'
                    .format(ref_frame, resid))
    method = method.lower()
    if method in ('frame', 'translate'):
        out = np.empty((len(X), len(R0), 3))
        local = R0 - CA0[owner]
        if method == 'frame':
            ta, tb, tc, usable = _frame_triples(CA0, ca_keys)
            F0 = _residue_frames(CA0, ta, tb, tc)
        for f, CA in enumerate(X):
            if method == 'translate':
                out[f] = R0 + (CA - CA0)[owner]
                continue
            F = _residue_frames(CA, ta, tb, tc)
            Rot = np.einsum('rij,rkj->rik', F, F0)          # F @ F0.T for every residue
            Rot[~usable] = np.eye(3)
            out[f] = CA[owner] + np.einsum('aij,aj->ai', Rot[owner], local)
        result = atoms.copy()
        result.setCoords(out)
        result.setTitle('{0} ({1} reconstruction)'.format(reference.getTitle(), method))
        return result
    if method != 'pulchra':
        raise ValueError("method must be 'frame', 'translate' or 'pulchra'")
    return _pulchra_path(X, ca, pulchra, scwrl, pulchra_args, keep_files)


def _which(exe, name):
    found = shutil.which(exe) if exe else None
    if found is None and exe and os.path.isfile(exe) and os.access(exe, os.X_OK):
        found = exe
    if found is None:
        raise EnvironmentError('{0} executable not found: {1!r}'.format(name, exe))
    return found


def _pulchra_path(X, ca, pulchra, scwrl, pulchra_args, keep_files):
    from prody.proteins import parsePDB, writePDB
    exe_p = _which(pulchra, 'PULCHRA')
    exe_s = _which(scwrl, 'SCWRL4') if scwrl else None
    folder = tempfile.mkdtemp(prefix='prody_pulchra_')
    template, coordsets, names = None, [], None
    trace = ca.copy()
    try:
        for f, CA in enumerate(X):
            trace.setCoords(CA)
            fin = os.path.join(folder, 'frame%05d.pdb' % f)
            writePDB(fin, trace)
            subprocess.run([exe_p] + list(pulchra_args) + [fin], check=True, cwd=folder,
                           stdout=subprocess.DEVNULL, stderr=subprocess.PIPE)
            built = fin[:-4] + '.rebuilt.pdb'
            if exe_s:
                packed = fin[:-4] + '.scwrl.pdb'
                subprocess.run([exe_s, '-i', built, '-o', packed], check=True, cwd=folder,
                               stdout=subprocess.DEVNULL, stderr=subprocess.PIPE)
                built = packed
            ag = parsePDB(built)
            key = list(zip(ag.getChids(), ag.getResnums(), ag.getNames()))
            if template is None:
                template, names = ag, key
                coordsets.append(ag.getCoords())
            else:
                if key != names:          # reorder to the atoms of the first frame
                    lookup = {k: i for i, k in enumerate(key)}
                    try:
                        order = [lookup[k] for k in names]
                    except KeyError:
                        raise ValueError('frame {0}: PULCHRA/SCWRL4 produced different atoms than frame 0'.format(f))
                    coordsets.append(ag.getCoords()[order])
                else:
                    coordsets.append(ag.getCoords())
    finally:
        if not keep_files:
            shutil.rmtree(folder, ignore_errors=True)
        else:
            LOGGER.info('buildAllAtomPath: per-frame files kept in {0}'.format(folder))
    result = template.copy()
    result.setCoords(np.array(coordsets))
    result.setTitle('{0} (PULCHRA{1} reconstruction)'.format(ca.getTitle(), ' + SCWRL4' if exe_s else ''))
    return result
