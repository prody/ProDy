# ---------------------------------------------------------------------------------------------------------------------
# decomposition of a conformational change over the modes of its start
# ---------------------------------------------------------------------------------------------------------------------

def calcDeformationModes(start, target, model='genanm', cutoff=15.0, gamma=1.0, fractions=(0.5, 0.8, 0.9),
                         n_soft=(5, 20), compact=0.03, diffuse=0.10, **kwargs):
    """Decompose the change from *start* to *target* over the normal modes of *start*.

    The target is superposed onto the start, and the deformation :math:`\\mathbf{d}` is projected on all nonzero
    modes. Optimal superposition makes :math:`\\mathbf{d}` orthogonal to the rigid-body motions of the start, so
    the squared overlaps :math:`O_k^2` sum to one over the nonzero modes.

    Returns a :class:`dict` with the overlaps ``'overlap'`` (signed correlation cosines), ``'share'``
    (:math:`O_k^2`), ``'cumulative'`` (cumulative share of the softest modes), the eigenvalues ``'eigvals'``,
    and the summaries ``'n<x>'`` (number of softest modes that carry the fraction x, for every x in *fractions*,
    for example ``'n80'``), ``'max_overlap'`` and ``'max_mode'`` (the best single mode, 1 = softest),
    ``'share_soft<K>'`` and ``'share_soft1pct'``, ``'stiffness_rel'`` (the share-weighted mean eigenvalue in units of
    the softest one), ``'n_eff'`` (inverse participation ratio of the shares), ``'collectivity'`` (of the residue
    displacements, after Brüschweiler), ``'rmsd'`` and ``'regime'``: *compact* when 80% of the change is carried by
    at most the fraction *compact* of the modes, *diffuse* when 50% needs more than the fraction *diffuse*, and
    *intermediate* otherwise.

    :arg start: start structure
    :type start: :class:`.Atomic`, :class:`~numpy.ndarray`

    :arg target: target structure, with atoms matching those of *start*
    :type target: :class:`.Atomic`, :class:`~numpy.ndarray`

    :arg model: ``'genanm'`` (default), ``'anm'``, or an :class:`.ANM` instance whose modes were calculated at the
        start (all nonzero modes are needed for the cumulative share to reach one)

    :arg cutoff: cutoff distance, default is 15 Å
    :arg gamma: spring constant, default is 1

    Other keyword arguments are passed to :meth:`.genANM.buildHessian`."""
    S = _coords(start, name='start')
    T = _coords(target, len(S), 'target')
    d = (_fit(T, S) - S).ravel()
    d2 = float(d @ d)
    if d2 == 0:
        raise ValueError('start and target are identical after superposition')
    if isinstance(model, str):
        _, enm = _network(S, model, cutoff, gamma, True, **kwargs)
        name = model
    else:
        enm = model
        name = type(model).__name__
    U = enm.getEigvecs()
    lam = enm.getEigvals()
    if U.shape[0] != len(d):
        raise ValueError('the modes do not match the structure')
    ov = (U.T @ d) / np.sqrt(d2)
    s = ov ** 2
    cum = np.cumsum(s)
    M = len(s)
    tot = float(cum[-1])
    out = dict(overlap=ov, share=s, cumulative=cum, eigvals=lam, n_modes=M, captured=tot,
               rmsd=float(np.sqrt(d2 / len(S))), model=name)
    for x in fractions:
        out['n%d' % int(round(100 * x))] = int(np.searchsorted(cum, x * tot) + 1)
    out['max_overlap'] = float(np.sqrt(s.max()))
    out['max_mode'] = int(np.argmax(s) + 1)
    for K in np.atleast_1d(n_soft):
        out['share_soft%d' % K] = float(cum[min(int(K), M) - 1])
    out['share_soft1pct'] = float(cum[max(0, int(np.ceil(0.01 * M)) - 1)])
    out['stiffness_rel'] = float((lam * s).sum() / s.sum() / lam[0])
    out['n_eff'] = float(s.sum() ** 2 / (s ** 2).sum())
    move = ((_fit(T, S) - S) ** 2).sum(1)
    p = move / move.sum()
    p = p[p > 0]
    out['collectivity'] = float(np.exp(-(p * np.log(p)).sum()) / len(S))
    n80 = out.get('n80', int(np.searchsorted(cum, 0.8 * tot) + 1))
    n50 = out.get('n50', int(np.searchsorted(cum, 0.5 * tot) + 1))
    out['regime'] = 'compact' if n80 <= compact * M else ('diffuse' if n50 > diffuse * M else 'intermediate')
    out['fractions'] = tuple(fractions)
    return out


