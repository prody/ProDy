def _network(X, model='anm', cutoff=15.0, gamma=1.0, modes=True, **kwargs):
    """Elastic network at coordinates X; returns (Hessian as dense array, model with all nonzero modes or None)."""
    from .anm import ANM
    from .generalized_anm import genANM
    name = model.lower() if isinstance(model, str) else model
    if name == 'anm':
        enm = ANM()
        enm.buildHessian(X, cutoff=cutoff, gamma=gamma)
    elif name == 'genanm':
        enm = genANM()
        enm.buildHessian(X, cutoff=cutoff, gamma=gamma, **kwargs)
    else:
        raise ValueError("model must be 'anm' or 'genanm'")
    H = enm.getHessian()
    H = H.toarray() if hasattr(H, 'toarray') else np.asarray(H)
    if modes:
        enm.calcModes(n_modes=None, zeros=False)
        return H, enm
    return H, None


def calcStepWork(path, target=None, model='anm', cutoff=15.0, gamma=1.0, n_soft=(5, 20), modes=True,
                 midpoints=False, **kwargs):
    """Return the elastic work of every step of *path* in the network of the conformation where the step starts,
    and the share of the step carried by the softest modes.

    For the displacement :math:`\\mathbf{D}` of a step, after its rigid-body motion has been removed by
    superposition, the work is :math:`W = \\frac{1}{2} \\mathbf{D}^T \\mathbf{H} \\mathbf{D}` and the effective
    stiffness :math:`\\eta = W / |\\mathbf{D}|^2`, which does not depend on the step size. The same network model is
    used for every step, so different paths of one system are measured on one yardstick.

    Per step (arrays): ``'work'``, ``'stiffness'``, ``'step_rms'`` (RMS displacement, Å), ``'rmsd_target'`` (at the
    end of the step, if *target* is given), ``'rmsd_gain'`` and ``'share_soft<K>'`` for every K in *n_soft*.

    Per path: ``'total_work'``, ``'work_per_A'`` (work per Å of RMSD progress, if *target* is given),
    ``'stiffness_path'`` and ``'stiffness_first_quarter'`` (sums of W over sums of :math:`|\\mathbf{D}|^2`),
    ``'share_soft<K>_path'`` (averages weighted by :math:`|\\mathbf{D}|^2`) and ``'cumulative_share'``, the
    weighted share of the motion carried by the softest 1, 2, ... modes.

    :arg path: the path
    :type path: :class:`.Ensemble`, :class:`.Atomic`, :class:`~numpy.ndarray`

    :arg target: target structure, used for the RMSD gain of each step
    :type target: :class:`.Atomic`, :class:`~numpy.ndarray`

    :arg model: network used as the yardstick, ``'anm'`` (default) or ``'genanm'``
    :type model: str

    :arg cutoff: cutoff distance, default is 15 Å
    :arg gamma: spring constant, default is 1
    :arg n_soft: numbers of softest modes whose shares are reported, default is (5, 20)
    :arg modes: decompose each step over the normal modes, default is **True**; **False** computes the work only,
        which is much faster for large proteins
    :arg midpoints: keep NeoAdaptiveANM midpoint frames as steps, default is **False**

    Other keyword arguments are passed to :meth:`.genANM.buildHessian`."""
    X = _frames(path)
    if not midpoints:
        X = dropMidpoints(X)
    n = X.shape[1]
    T = _coords(target, n, 'target')
    if len(X) < 2:
        raise ValueError('the path has fewer than two frames')
    n_soft = tuple(int(k) for k in np.atleast_1d(n_soft))
    rows = dict(work=[], stiffness=[], step_rms=[], rmsd_target=[], rmsd_gain=[])
    shares = {k: [] for k in n_soft}
    cum, sq = None, []
    rmsd_prev = _rmsd_fit(X[0], T) if T is not None else None
    for k in range(len(X) - 1):
        A = X[k]
        D = (_fit(X[k + 1], A) - A).ravel()
        dd = float(D @ D)
        H, enm = _network(A, model, cutoff, gamma, modes, **kwargs)
        W = 0.5 * float(D @ H @ D)
        sq.append(dd)
        rows['work'].append(W)
        rows['stiffness'].append(W / dd if dd > 0 else np.nan)
        rows['step_rms'].append(np.sqrt(dd / n))
        if T is not None:
            r = _rmsd_fit(X[k + 1], T)
            rows['rmsd_target'].append(r)
            rows['rmsd_gain'].append(rmsd_prev - r)
            rmsd_prev = r
        if modes:
            c = (enm.getEigvecs().T @ D) ** 2
            tot = c.sum() if c.sum() > 0 else 1.0
            for K in n_soft:
                shares[K].append(float(c[:K].sum() / tot))
            w = np.cumsum(c) / tot * dd
            cum = w if cum is None else cum[:len(w)] + w[:len(cum)]
    out = {key: np.array(val) for key, val in rows.items()}
    out['step'] = np.arange(1, len(X))
    sq = np.array(sq)
    E = out['work']
    q = max(1, len(E) // 4)
    out['squared_step'] = sq
    out['total_work'] = float(E.sum())
    out['stiffness_path'] = float(E.sum() / sq.sum()) if sq.sum() > 0 else np.nan
    out['stiffness_first_quarter'] = float(E[:q].sum() / sq[:q].sum()) if sq[:q].sum() > 0 else np.nan
    if T is not None:
        gain = float(out['rmsd_gain'].sum())
        out['rmsd_start'] = _rmsd_fit(X[0], T)
        out['work_per_A'] = out['total_work'] / gain if gain > 0 else np.nan
    if modes:
        for K in n_soft:
            out['share_soft%d' % K] = np.array(shares[K])
            out['share_soft%d_path' % K] = float((np.array(shares[K]) * sq).sum() / sq.sum())
        out['cumulative_share'] = cum / sq.sum()
    out['model'] = model
    return out


def showStepWork(work, label=None, color=None, axes=None, **kwargs):
    """Plot the result of :func:`calcStepWork` in three panels: cumulative elastic work against RMSD progress toward
    the target (or against the step number when no target was given), the effective stiffness of each step, and the
    cumulative share of the motion against mode rank. Call again with the returned *axes* to compare paths.

    :arg work: output of :func:`calcStepWork`
    :arg label: legend label for this path
    :arg color: line colour
    :arg axes: three Matplotlib axes to draw on, default is a new figure

    Returns the list of axes."""
    w = work
    n_panels = 3 if 'cumulative_share' in w else 2
    if axes is None:
        import matplotlib.pyplot as plt
        fig, axs = plt.subplots(1, n_panels, figsize=(5.0 * n_panels, 4.0))
        fig.subplots_adjust(wspace=0.36)
