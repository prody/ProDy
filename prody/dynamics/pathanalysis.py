def _frames(path):
    """Return path frames as a float array of shape (n_frames, n_atoms, 3)."""
    if isinstance(path, Ensemble):
        X = path.getCoordsets()
    elif isinstance(path, Atomic):
        X = path.getCoordsets()
    else:
        X = np.asarray(path, dtype=float)
    X = np.asarray(X, dtype=float)
    if X.ndim == 2:
        X = X[None]
    if X.ndim != 3 or X.shape[2] != 3:
        raise ValueError('path must have shape (n_frames, n_atoms, 3)')
    return X


def _coords(struct, n_atoms=None, name='structure'):
    """Return a single structure as a float array of shape (n_atoms, 3)."""
    if struct is None:
        return None
    if isinstance(struct, Atomic):
        X = struct.getCoords()
    else:
        X = np.asarray(struct, dtype=float)
    X = np.asarray(X, dtype=float)
    if X.ndim != 2 or X.shape[1] != 3:
        raise ValueError('{0} must have shape (n_atoms, 3)'.format(name))
    if n_atoms is not None and len(X) != n_atoms:
        raise ValueError('{0} has {1} atoms; the path has {2}'.format(name, len(X), n_atoms))
    return X


def _kabsch(X, Y):
    """Rotation matrix and translation that superpose X onto Y (both (n, 3)); X @ R + t."""
    xc, yc = X.mean(0), Y.mean(0)
    H = (X - xc).T @ (Y - yc)
    U, _, Vt = np.linalg.svd(H)
    d = np.sign(np.linalg.det(U @ Vt))
    D = np.diag([1.0, 1.0, d])
    R = U @ D @ Vt
    return R, yc - xc @ R


def _fit(X, Y):
    """X superposed onto Y."""
    R, t = _kabsch(X, Y)
    return X @ R + t


def _rmsd_fit(X, Y):
    """RMSD between X and Y after optimal superposition."""
    return float(np.sqrt(((_fit(X, Y) - Y) ** 2).sum(1).mean()))


def _rmsd_fit_many(X, Ys):
    """RMSD after optimal superposition between one structure X (n, 3) and many structures Ys (m, n, 3)."""
    Xc = X - X.mean(0)
    Yc = Ys - Ys.mean(1)[:, None, :]
    H = np.einsum('ni,mnj->mij', Xc, Yc)
    U, S, Vt = np.linalg.svd(H)
    d = np.sign(np.linalg.det(np.einsum('mij,mjk->mik', U, Vt)))
    S[:, 2] *= d
    e = (Xc ** 2).sum() + (Yc ** 2).sum(axis=(1, 2)) - 2.0 * S.sum(1)
    return np.sqrt(np.maximum(e, 0.0) / len(X))


def _bond_lengths(X):
    return np.linalg.norm(X[..., 1:, :] - X[..., :-1, :], axis=-1)


def _arc_fraction(frames):
    """Cumulative RMS displacement along consecutive frames, normalized to [0, 1]."""
    if len(frames) < 2:
        return np.zeros(len(frames))
    step = np.sqrt(((frames[1:] - frames[:-1]) ** 2).sum(-1).mean(-1))
    s = np.concatenate([[0.0], np.cumsum(step)])
    return s / s[-1] if s[-1] > 0 else s


def _style_axes(ax, xlabel=None, ylabel=None, title=None):
    if xlabel:
        ax.set_xlabel(xlabel, fontsize=FONTSIZE)
    if ylabel:
        ax.set_ylabel(ylabel, fontsize=FONTSIZE)
    if title:
        ax.set_title(title, fontsize=FONTSIZE + 1, loc='left')
    ax.tick_params(labelsize=FONTSIZE - 1)
    for side in ('top', 'right'):
        ax.spines[side].set_visible(False)
    ax.grid(alpha=0.25, lw=0.6)


def _axes(n, axes=None, width=5.2, height=3.9):
    import matplotlib.pyplot as plt
    if axes is not None:
        axes = list(np.ravel(axes))
        if len(axes) < n:
            raise ValueError('{0} axes are needed'.format(n))
        return axes[:n]
    ncol = min(n, 2) if n > 1 else 1
    nrow = int(np.ceil(n / float(ncol)))
    fig, axs = plt.subplots(nrow, ncol, figsize=(width * ncol, height * nrow), squeeze=False)
    axs = list(axs.ravel())
    for extra in axs[n:]:
        extra.set_visible(False)
    fig.subplots_adjust(wspace=0.32, hspace=0.42)
    return axs[:n]


