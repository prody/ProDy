def calcPathPCA(paths, structures=None, reference=None, n_components=2):
    """Principal component analysis of the frames of one or more paths, all superposed onto one reference, so that
    different routes between the same states can be seen in one plane.

    Returns a :class:`dict` with ``'projections'`` (one array of shape (n_frames, n_components) per path),
    ``'structures'`` (projections of the additional *structures*, such as endpoints or intermediates),
    ``'variance'`` (fraction of the variance per component), ``'components'`` and ``'mean'``.

    :arg paths: a path or a list of paths with the same atoms
    :arg structures: additional structures to project, for example the endpoints
    :arg reference: structure every frame is superposed onto, default is the last frame of the first path
    :arg n_components: number of components, default is 2"""
    if isinstance(paths, (Ensemble, Atomic, np.ndarray)) and not isinstance(paths, list):
        paths = [paths]
    P = [_frames(p) for p in paths]
    n = P[0].shape[1]
    ref = _coords(reference, n, 'reference') if reference is not None else P[0][-1]
    al = [np.array([_fit(x, ref) for x in p]) for p in P]
    st = [_fit(_coords(s, n), ref) for s in (structures or [])]
    A = np.vstack([p.reshape(len(p), -1) for p in al] + [s.reshape(1, -1) for s in st])
    mu = A.mean(0)
    _, sv, Vt = np.linalg.svd(A - mu, full_matrices=False)
    comp = Vt[:n_components]
    proj = lambda M: (M.reshape(len(M), -1) - mu) @ comp.T
    var = sv ** 2 / (sv ** 2).sum()
    return dict(projections=[proj(p) for p in al], structures=[proj(s[None])[0] for s in st],
                variance=var[:n_components], components=comp, mean=mu)


